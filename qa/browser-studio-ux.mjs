import assert from 'node:assert/strict'
import { join } from 'node:path'

export async function studioUx({ page, frame, sdk, source, replaceDocument, waitForSource, session, output, evidence }) {
  const original = JSON.parse((await source()).text)
  const header = frame.locator('.studio-timeline-row[data-track-id="lead"] .studio-track-label')
  assert.equal(await frame.locator('.studio-transport').getByRole('button', { name: 'Сохранить', exact: true }).count(), 0)
  await header.getByRole('button', { name: 'Заглушить Lead synth', exact: true }).click()
  await waitForSource(doc => doc.tracks[0].muted)
  await header.getByRole('button', { name: 'Заглушить Lead synth', exact: true }).click()
  await waitForSource(doc => !doc.tracks[0].muted)
  await header.press('Shift+F10')
  await frame.getByRole('menuitem', { name: 'Название, цвет и значок', exact: true }).click()
  const dialog = frame.getByRole('dialog', { name: 'Название, цвет и значок', exact: true })
  await dialog.getByRole('textbox', { name: 'Имя', exact: true }).fill('Звук QA')
  await dialog.getByRole('textbox', { name: 'Цвет дорожки', exact: true }).fill('#cc5577')
  await dialog.getByRole('combobox', { name: 'Значок', exact: true }).click()
  await frame.getByRole('option', { name: 'Микрофон', exact: true }).click()
  await dialog.getByRole('button', { name: 'Сохранить', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
  await waitForSource(doc => doc.tracks[0].name === 'Звук QA' && doc.tracks[0].color === '#cc5577' && doc.tracks[0].icon === 'mic')
  await page.locator('.editor-toolbar__save').click()
  await header.press('F2'); await dialog.waitFor(); await dialog.getByRole('textbox', { name: 'Имя', exact: true }).fill('Отмена'); await dialog.press('Escape')
  assert.equal(JSON.parse((await source()).text).tracks[0].name, 'Звук QA')
  await header.click({ button: 'right' }); await frame.getByRole('menuitem', { name: 'Дублировать', exact: true }).click()
  await waitForSource(doc => doc.tracks.length === 2)
  const copy = frame.locator('.studio-timeline-row').last().locator('.studio-track-label')
  await copy.click({ button: 'right' }); await frame.getByRole('menuitem', { name: 'Удалить дорожку', exact: true }).click()
  await waitForSource(doc => doc.tracks.length === 1)
  const mode = frame.getByRole('combobox', { name: 'Режим воспроизведения', exact: true })
  await mode.click(); await frame.getByRole('option', { name: 'Паттерн', exact: true }).click()
  await page.waitForTimeout(500)
  await frame.getByRole('button', { name: 'Воспроизвести / пауза', exact: true }).click()
  await page.waitForTimeout(2400)
  const pattern = await sdk('poll', { session })
  assert.ok(pattern.playing && pattern.frame < 96000, 'Pattern preview loops at its own length')
  assert.equal(JSON.parse((await source()).text).loop.end, original.loop.end, 'Audition does not mutate song')
  await frame.getByRole('button', { name: 'Стоп', exact: true }).click()
  await mode.click(); await frame.getByRole('option', { name: 'Композиция', exact: true }).click()
  await page.waitForTimeout(300)
  const long = structuredClone(original); long.patterns[0].length = 245760; long.tracks[0].clips[0].length = 245760; long.loop.end = 245760
  await replaceDocument(long)
  const follow = frame.getByRole('button', { name: 'Следовать за воспроизведением', exact: true })
  assert.equal(await follow.getAttribute('aria-pressed'), 'true')
  await sdk('engine', { session, command: 'seek', arguments: { frame: 48000 * 35 } })
  await frame.getByRole('button', { name: 'Воспроизвести / пауза', exact: true }).click()
  await page.waitForTimeout(650)
  const left = await frame.locator('.studio-arrangement-scroll').evaluate(el => el.scrollLeft)
  assert.ok(left > 100, 'Arrangement follows playhead near viewport edge')
  assert.ok(await frame.locator('.studio-piano-scroll').first().evaluate(el => el.scrollLeft) > 100, 'Piano roll follows too')
  await follow.click()
  await sdk('engine', { session, command: 'seek', arguments: { frame: 48000 * 80 } })
  await page.waitForTimeout(400)
  assert.equal(await frame.locator('.studio-arrangement-scroll').evaluate(el => el.scrollLeft), left, 'Follow off preserves manual viewport')
  await frame.getByRole('button', { name: 'Стоп', exact: true }).click(); await follow.click()
  for (const theme of ['light', 'dark']) {
    await page.evaluate(theme => { document.documentElement.dataset.theme = theme }, theme)
    await frame.waitForFunction(theme => window.devline.getContext().theme === theme, theme)
    await frame.locator('[data-auto-hide-tool="mixer"]').click()
    await frame.locator('.ui-tool-dock__panel--floating.is-open').waitFor()
    await page.waitForTimeout(250)
    const bounds = await frame.locator('.ui-tool-dock').first().evaluate(el => {
      const right = el.querySelector('.ui-tool-dock__panel--right:not(.ui-tool-dock__panel--floating)').getBoundingClientRect()
      const lower = el.querySelector('.ui-tool-dock__panel--bottom:not(.ui-tool-dock__panel--floating)').getBoundingClientRect()
      const flyout = el.querySelector('.ui-tool-dock__panel--floating.is-open').getBoundingClientRect()
      return { rightLeft: right.left, rightBottom: right.bottom, lowerRight: lower.right, lowerBottom: lower.bottom, flyoutRight: flyout.right }
    })
    assert.ok(Math.abs(bounds.lowerRight - bounds.rightLeft) <= 1 && Math.abs(bounds.flyoutRight - bounds.rightLeft) <= 1 && Math.abs(bounds.lowerBottom - bounds.rightBottom) <= 1, JSON.stringify(bounds))
    await page.screenshot({ path: join(output, `studio-ux-${theme}.png`), animations: 'disabled' })
    await frame.locator('[data-auto-hide-tool="mixer"]').click()
  }
  await replaceDocument(original)
  await frame.locator('.studio-arrangement-scroll').evaluate(el => { el.scrollLeft = 0 })
  await frame.locator('.studio-piano-scroll').first().evaluate(el => { el.scrollLeft = 0 })
  if (process.env.SOUND_QA_UX_VST === '1') {
    assert.match(process.env.DEVLINE_NATIVE_QA_DESKTOP ?? '', /^DevLine-QA-/)
    await frame.locator('[data-auto-hide-tool="instruments"]').click()
    await frame.getByRole('textbox', { name: 'Каталог VST3', exact: true }).fill('C:/Program Files/Common Files/VST3/Serum2.vst3')
    await frame.getByRole('button', { name: 'Найти плагины VST3', exact: true }).click()
    await frame.getByRole('button', { name: 'Добавить Serum 2', exact: true }).click({ timeout: 30000 })
    await waitForSource(doc => doc.tracks.some(track => track.instrument.kind === 'vst3'))
    await frame.locator('.studio-timeline').click({ position: { x: 250, y: 190 } })
    await page.waitForTimeout(500)
    const params = frame.getByRole('button', { name: 'Параметры', exact: true })
    await params.click()
    const modal = frame.getByRole('dialog', { name: 'Параметры: Serum 2', exact: true })
    await modal.waitFor()
    await modal.getByRole('slider').first().waitFor()
    assert.ok(await modal.getByRole('slider').count() <= 64)
    assert.equal(await frame.locator('.studio-property-grid input[type=range]').count(), 1, 'Only swing slider remains in inspector')
    const firstName = await modal.getByRole('slider').first().getAttribute('aria-label')
    await modal.getByRole('button', { name: 'Следующая страница', exact: true }).click()
    await page.waitForTimeout(300)
    assert.notEqual(await modal.getByRole('slider').first().getAttribute('aria-label'), firstName)
    await modal.getByRole('textbox', { name: 'Поиск по имени или ID', exact: true }).fill('516000001')
    await page.waitForTimeout(500)
    assert.equal(await modal.getByRole('slider').count(), 1)
    await page.screenshot({ path: join(output, 'vst-parameter-search.png'), animations: 'disabled' })
    await modal.press('Escape'); await modal.waitFor({ state: 'hidden' })
    await params.click(); await modal.waitFor(); await modal.getByRole('slider').first().waitFor()
    await modal.getByRole('slider').first().press('ArrowLeft')
    await page.waitForTimeout(250)
    await modal.getByRole('button', { name: 'Закрыть', exact: true }).click()
    await modal.waitFor({ state: 'hidden' })
    await page.locator('.editor-toolbar__save').click()
    await waitForSource((_doc, state) => !state.dirty)
    assert.ok(!(await sdk('poll', { session })).engineError)
    evidence.vstParameterModal = { boundedPage: 64, searchLastParameter: true, keyboardEditAndSave: true }
    await replaceDocument(original)
    await frame.waitForFunction(() => document.querySelectorAll('.studio-timeline-row').length === 1)
  }
  evidence.studioUx = { trackMetadata: true, contextMenuKeyboard: true, mute: true, patternAudition: true, followPlayhead: true, alignedDockCorners: true, oneSaveButton: true }
}
